import { readFile, writeFile, readdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';

// Dependency order is captured from Ext.Loader by check-frontend-boot.mjs.
// Building and checking an existing inventory require only Node.js, not Sencha Cmd.
const root = resolve(import.meta.dirname, '..');
const captureArg = process.argv.find(arg => arg.startsWith('--capture='));
if (captureArg) {
    const capture = JSON.parse(await readFile(resolve(root, captureArg.slice('--capture='.length)), 'utf8'));
    const byName = new Map(capture.definitions.map(definition => [definition.name, definition]));
    const definitions = [...capture.history.map(name => byName.get(name)), ...capture.definitions.filter(definition => definition.override)];
    const paths = [...new Set(definitions.filter(definition => definition && definition.path && definition.path !== 'app.js' && !definition.path.startsWith('resources/locale/')).map(definition => definition.path))];
    if (!paths.includes('classic/src/Application.js')) throw new Error('Capture did not include the application');
    await writeFile(resolve(root, 'script/frontend-sources.json'), JSON.stringify(paths, null, 2) + '\n');
}
const inventory = JSON.parse(await readFile(resolve(root, 'script/frontend-sources.json'), 'utf8'));
const parts = ['/* Generated by node script/build-frontend.mjs. Edit the source files, then rebuild. */\n'];
for (const path of inventory) {
    if (!/^(?:app|classic\/src|ext\/packages)\/[\w/.-]+\.js$/.test(path) || path.includes('..') || path === 'app.js') throw new Error(`Invalid source path: ${path}`);
    parts.push(`\n;\n/* Source: ${path} */\n`, (await readFile(resolve(root, path), 'utf8')).replace(/\r\n/g, '\n'), '\n');
}
const bundle = parts.join('');
const app = (await readFile(resolve(root, 'app.js'), 'utf8')).replace(/\r\n/g, '\n');
const revision = createHash('sha256').update(bundle).update(app).digest('hex').slice(0, 16);
const js = [{path:'ext/build/ext-all.js'}, {path:`resources/mbilling-bundle.js?v=${revision}`}, {path:`app.js?v=${revision}`}];
const outputs = new Map([['resources/mbilling-bundle.js', bundle]]);
for (const path of await readdir(root)) {
    if (!/^[a-z]+-[a-z]+\.json$/.test(path)) continue;
    const manifest = JSON.parse(await readFile(resolve(root, path), 'utf8'));
    if (manifest.name !== 'MBilling' || !Array.isArray(manifest.js)) continue;
    manifest.js = js;
    manifest.hash = revision;
    outputs.set(path, JSON.stringify(manifest) + '\n');
}
for (const [path, contents] of outputs) {
    if (process.argv.includes('--check')) {
        const actual = (await readFile(resolve(root, path), 'utf8')).replace(/\r\n/g, '\n');
        if (actual !== contents) throw new Error(`${path} is stale; run node script/build-frontend.mjs`);
    } else await writeFile(resolve(root, path), contents);
}
console.log(`${process.argv.includes('--check') ? 'Verified' : 'Built'} ${inventory.length} sources (${Buffer.byteLength(bundle)} bytes), revision ${revision}, ${outputs.size - 1} manifests`);
